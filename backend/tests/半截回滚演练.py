"""半截装载回滚·口径甲演练（直接运行：python tests/半截回滚演练.py）。

夹具剧本：
一、正常批（号卡套餐样例）→ 成功，三族该批增量与事务证据齐全；
二、中段必失败批（半截失败样例）→ 三族无该批增量且批次非成功；
三、同批号重试 → 被拒（批号一次性，无重试/补偿交错窗口）；
四、故意留下补偿残留（外带植入失败批批号的枢纽行）→ 贯验必须失败
    （口径甲：装载服务无删除/补偿路径，残留只能外带植入，且必被打败）；
五、造补偿未完即标终结（伪成功批、无装载事务日志）→ 必须失败闭；
六、造悬挂未终结批（装载中）→ 必须失败闭；
七、造无账增量（正式表批号无台账）→ 必须失败；
八、造正式已清扫而批次仍成功（删成功批一笔卫星）→ 必须失败；
九、全部清理后贯验恢复通过。
"""
import json
import os
import sys
import tempfile
from pathlib import Path

后端 = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(后端))
os.environ["数据目录"] = tempfile.mkdtemp(prefix="号枢半截演练")
os.environ["夹具目录"] = str(后端.parent / "fixtures")

from app import seed  # noqa: E402
from app.db import 连接  # noqa: E402
from app.services import 装载, 贯验  # noqa: E402

过 = 0


def 断(条件, 名):
    global 过
    if not 条件:
        print(f"  ✗ {名}")
        raise SystemExit(1)
    过 += 1
    print(f"  ✓ {名}")


def 装夹具(名):
    体 = json.loads((Path(os.environ["夹具目录"]) / f"{名}.json").read_text(encoding="utf-8"))
    return 装载.装一批(体)


def 改库(sql, 参=()):
    conn = 连接()
    try:
        conn.execute(sql, 参)
        conn.commit()
    finally:
        conn.close()


def 主():
    seed.初始化库()

    print("一·正常批：增量与事务证据齐全")
    r = 装夹具("号卡套餐样例")
    断(r["结果"] == "成功", "样例批装载成功")
    v = 贯验.查半截回滚("批-样例-01")
    断(v["成败"] is True and v["批次状态"] == "成功", "接口：批次成功标志为真")
    断(v["增量"] == {"枢纽": 6, "链接": 4, "卫星": 8, "合计": 18}, "接口：三族该批增量正确")
    断(v["证据"]["事务日志"] == "存在" and v["贯验通过"], "接口：同事务证据齐全且贯验通过")

    print("二·中段必失败批：三族零增量且批次非成功")
    r = 装夹具("半截失败样例")
    断(r["结果"] == "失败", "中段失败返回失败")
    v = 贯验.查半截回滚("批-半截-01")
    断(v["批次状态"] == "失败" and v["成败"] is False, "批次非成功")
    断(v["增量"]["合计"] == 0, "三族该批增量为零（事务整体回滚）")
    断(v["贯验通过"], "失败批零残留：一致性通过")
    断(贯验.跑贯验()["是否通过"], "全局贯验不受干净失败批影响")

    print("三·同批号重试被拒")
    r = 装夹具("半截失败样例")
    断(r["结果"] == "拒绝" and "一次性" in r["说明"], "同批号重试被拒，重试须换新批号")

    print("四·故意留下补偿残留：甲无残留路径，外带植入亦必败")
    源 = (后端 / "app/services/装载.py").read_text(encoding="utf-8")
    断("DELETE" not in 源.upper(), "装载服务无删除/补偿路径（甲：不应出现残留路径）")
    改库("INSERT INTO 枢纽_号卡(哈希键, 业务键, 装载日, 批号) VALUES('伪哈希-残留','卡-残留','2026-11-22','批-半截-01')")
    v = 贯验.查半截回滚("批-半截-01")
    断(not v["贯验通过"] and any("残留" in p for p in v["问题"]), "失败批残留被单批接口判失败")
    断(not 贯验.扫半截回滚()["贯验通过"], "全量扫描判失败")
    g = 贯验.跑贯验()
    检 = {x["名"]: x for x in g["检项"]}
    断(not g["是否通过"] and not 检["半截回滚零残留"]["通过"], "全局贯验判失败")
    改库("DELETE FROM 枢纽_号卡 WHERE 哈希键='伪哈希-残留'")
    断(贯验.查半截回滚("批-半截-01")["贯验通过"], "清理残留后恢复通过")

    print("五·补偿未完即标终结（伪成功、无事务日志）→ 失败闭")
    改库("INSERT INTO 装载批次(编号, 装载日, 时刻, 状态, 事务号, 报告) VALUES('批-伪终结-01','2026-11-22','2026-11-22T00:00:00Z','成功','伪事务号','{}')")
    v = 贯验.查半截回滚("批-伪终结-01")
    断(not v["贯验通过"] and any("事务" in p for p in v["问题"]), "标成功却无同事务证据被判失败")
    断(not 贯验.跑贯验()["是否通过"], "全局贯验失败闭")
    改库("DELETE FROM 装载批次 WHERE 编号='批-伪终结-01'")

    print("六·悬挂未终结批（装载中）→ 失败闭")
    改库("INSERT INTO 装载批次(编号, 装载日, 时刻, 状态, 事务号) VALUES('批-悬挂-01','2026-11-22','2026-11-22T00:00:00Z','装载中','悬挂事务')")
    v = 贯验.查半截回滚("批-悬挂-01")
    断(v["成败"] is False and not v["贯验通过"], "未终结批非成功且判失败")
    断(not 贯验.跑贯验()["是否通过"], "全局贯验失败闭")
    改库("DELETE FROM 装载批次 WHERE 编号='批-悬挂-01'")

    print("七·无账增量 → 失败")
    改库("INSERT INTO 枢纽_套餐(哈希键, 业务键, 装载日, 批号) VALUES('伪哈希-无账','套-无账','2026-11-22','批-无账-01')")
    断(not 贯验.扫半截回滚()["贯验通过"], "无台账批号被全量扫描判失败")
    断(not 贯验.查半截回滚("批-无账-01")["贯验通过"], "单批接口判失败")
    改库("DELETE FROM 枢纽_套餐 WHERE 哈希键='伪哈希-无账'")

    print("八·正式已清扫而批次仍成功 → 失败")
    conn = 连接()
    try:
        行 = conn.execute("SELECT * FROM 卫星_客户属性 WHERE 批号='批-样例-01' LIMIT 1").fetchone()
    finally:
        conn.close()
    断(行 is not None, "取成功批卫星样本")
    改库("DELETE FROM 卫星_客户属性 WHERE 编号=?", (行["编号"],))
    v = 贯验.查半截回滚("批-样例-01")
    断(not v["贯验通过"] and any("不符" in p for p in v["问题"]), "增量与批次报告分叉被判失败")
    断(not 贯验.跑贯验()["是否通过"], "全局贯验失败闭")
    改库(
        "INSERT INTO 卫星_客户属性(编号, 客户哈希, 装载日, 载荷哈希, 属性, 是否当前, 批号) VALUES (?,?,?,?,?,?,?)",
        (行["编号"], 行["客户哈希"], 行["装载日"], 行["载荷哈希"], 行["属性"], 行["是否当前"], 行["批号"]),
    )

    print("九·清理后恢复")
    断(贯验.跑贯验()["是否通过"], "全部污染清理后贯验恢复通过")
    print(f"\n演练通过：{过} 项断言全过")


if __name__ == "__main__":
    主()
